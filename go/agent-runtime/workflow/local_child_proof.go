// OwnsKernelRuntime proves the built-in Workflow creates and resumes Runs
// in the exact Kernel the Harness controls, rather than a foreign Runtime.
func (runner *Runner) OwnsKernelRuntime(runtime *kernel.Runtime) bool {
	return runner != nil && runtime != nil && runner.runtime == runtime
}

// RecordsRelationsTo proves the original Workflow indexes physical effect
// descendants in the exact registry Harness reads for cancellation.
func (runner *Runner) RecordsRelationsTo(recorder runrelation.Recorder) bool {
	return runner != nil && runrelation.SameRecorder(runner.relations, recorder)
}

// UsesLocalAgentRunner proves that the original, statically bound AgentTask
// executor will resume approvals through the exact Harness Agent, including
// its Host middleware, preparer and Tool policies. Same Kernel is not enough.
func (runner *Runner) UsesLocalAgentRunner(runtime *kernel.Runtime, candidate *agent.Runner) bool {
	if runner == nil || runtime == nil || candidate == nil || runner.runtime != runtime {
		return false
	}
	owner := runner.localAgentTaskOwner()
	return owner != nil && owner.LocalAgentTaskRunner() == candidate && candidate.ObservesKernelRuntime(runtime)
}

func (runner *Runner) localAgentTaskOwner() LocalAgentTaskOwner {
	if runner == nil {
		return nil
	}
	router, ok := runner.effects.(*StaticEffectRouter)
	if !ok {
		return nil
	}
	return router.localAgentTaskOwner(runner.relations)
}

func (runner *Runner) localAgentTaskWaitingCancellationFenced() bool {
	if runner == nil {
		return false
	}
	router, ok := runner.effects.(*StaticEffectRouter)
	return ok && router.localAgentTaskWaitingCancellationFenced(runner.relations)
}

// VerifyLocalChild proves only built-in subworkflows or a statically bound
// AgentTask executed by this Kernel and indexed by its original recorder.
// Arbitrary EffectExecutor children have no inferred local authority, even if
// a local Run has identical metadata. The Harness proves the entire parent
// chain and its own recorder identity independently.
func (runner *Runner) VerifyLocalChild(runtime *kernel.Runtime, parent kernel.Snapshot, relation runrelation.Relation, child kernel.Snapshot, control bool) bool {
	if runner == nil || runtime == nil || runner.runtime != runtime ||
		parent.Run.Kind != RunKind ||
		relation.Kind != runrelation.KindWorkflowEffect || relation.ParentRunID != parent.Run.ID ||
		relation.ChildRunID != child.Run.ID || relation.OwnerNodeID == "" ||
		child.Run.Actor != parent.Run.Actor || child.Run.Thread != parent.Run.Thread {
		return false
	}
	state, err := decodeExecutionState(parent.State)
	if err != nil {
		return false
	}
	if child.Run.Kind == agent.RunKind {
		return runner.verifyLocalAgentTaskChild(runtime, state, relation, child, control)
	}
	if child.Run.Kind != RunKind || runner.registry == nil {
		return false
	}
	for _, effect := range state.Effects {
		if effect.Class != EffectClassSubworkflow || effect.ChildRunID != relation.ChildRunID ||
			effect.Definition == nil || !validDefinitionReference(*effect.Definition) ||
			effect.NestedDepth <= 0 {
			continue
		}
		ownerMatches := relation.OwnerNodeID == effectRelationOwnerID(effect)
		// ensureEffectRelation preserves historical node-owned fan-out relations.
		if (effect.OutputKey != "" || effect.Mapped) && relation.OwnerNodeID == effect.NodeID {
			ownerMatches = true
		}
		if !ownerMatches {
			continue
		}
		return verifiedSubworkflowChildOrigin(EffectRequest{
			EffectID: effect.ID, Actor: parent.Run.Actor, Thread: parent.Run.Thread,
			Definition: effect.Definition, NestedDepth: effect.NestedDepth, Input: effect.Input,
		}, child)
	}
	return false
}

// A persisted AgentTask child requires an unambiguous, current Effect attempt
// and the exact child identity generated by its Host executor. Requiring an
// original route object and its recorder avoids a same-ID remote/local twin.
// Reads and approval observations may use a Host-prepared Agent; physical
// cancellation requires its own Kernel fence or a proven quiescent pending
// checkpoint with a frozen Harness admission route. Terminal Runs are
// only verified read-only for settlement, never re-dispatched.
func (runner *Runner) verifyLocalAgentTaskChild(runtime *kernel.Runtime, state executionState, relation runrelation.Relation, child kernel.Snapshot, control bool) bool {
	owner := runner.localAgentTaskOwner()
	if owner == nil {
		return false
	}
	original := owner.LocalAgentTaskRunner()
	if original == nil || !original.ObservesKernelRuntime(runtime) {
		return false
	}
	terminalObserved := verifiedAgentTaskTerminalObservation(child)
	if control {
		switch child.Run.Status {
		case kernel.RunStatusCompleted, kernel.RunStatusFailed, kernel.RunStatusCancelled:
			// Native and Host-prepared Agents share the same physical Tool
			// settlement requirement: a terminal Kernel CAS does not cancel
			// an unacknowledged external operation.
			if !terminalObserved {
				return false
			}
		case kernel.RunStatusRunning, kernel.RunStatusWaitingInput, kernel.RunStatusPausedBudget:
		default:
			return false
		}
	}
	if control && !original.OwnsKernelRuntime(runtime) && !terminalObserved &&
		(!runner.localAgentTaskWaitingCancellationFenced() ||
			!original.QuiescentApprovalCancellation(runtime, child)) {
		return false
	}
	matches := 0
	for _, effect := range state.Effects {
		if effect.Class != EffectClassAgent || effect.Attempt <= 0 ||
			(effect.Status != EffectPending && effect.Status != EffectCompleted) ||
			effect.ChildRunID != child.Run.ID ||
			agentTaskChildRunID(effect) != child.Run.ID ||
			effect.ID != child.Run.RequestID || child.Run.Goal == "" ||
			effect.Compensation || effect.OutputKey != "" || effect.Mapped ||
			relation.OwnerNodeID != effectRelationOwnerID(effect) ||
			!matchesAgentTaskNode(state.Definition, effect) ||
			!matchesAgentTaskActivation(state.Activations, effect) ||
			!validAgentTaskEffectChildState(effect, child) ||
			!owner.VerifyAgentTaskOrigin(effect, child) {
			continue
		}
		matches++
	}
	return matches == 1
}

// A terminal child requires no new physical Cancel callback: Harness checks
// the original immutable route and then reads the already committed Kernel
// terminal status before invoking its Canceller. Keep this narrow read-only
// reconciliation path separate from the proof that authorizes an actual
// waiting-input cancellation with Host middleware. A malformed completed Run
// must never be treated as settled output.
func verifiedAgentTaskTerminalObservation(child kernel.Snapshot) bool {
	if !agent.TerminalPhysicalEffectsSettled(child) {
		return false
	}
	switch child.Run.Status {
	case kernel.RunStatusCompleted:
		return child.Result != nil && json.Valid(child.Result.Content)
	case kernel.RunStatusFailed, kernel.RunStatusCancelled:
		return true
	case kernel.RunStatusRunning, kernel.RunStatusWaitingInput, kernel.RunStatusPausedBudget:
		return false
	default:
		return false
	}
}

// A parent may observe a completed child before consuming its receipt, but
// after committing EffectCompleted it must retain the *same* child terminal
// receipt and output. A completed Effect with a waiting or unrelated child
// cannot authorize approval, cancellation or result projection.
func validAgentTaskEffectChildState(effect Effect, child kernel.Snapshot) bool {
	if effect.Status == EffectPending {
		return true
	}
	if effect.Status != EffectCompleted || child.Run.Status != kernel.RunStatusCompleted ||
		child.Result == nil || effect.ReceiptID != child.Run.ID {
		return false
	}
	return len(effect.Output) != 0 && json.Valid(effect.Output) &&
		json.Valid(child.Result.Content) &&
		bytes.Equal(normalizeJSON(effect.Output), normalizeJSON(child.Result.Content))
}

func agentTaskChildRunID(effect Effect) string {
	if effect.ID == "" || strings.TrimSpace(effect.ID) != effect.ID || effect.Attempt <= 0 {
		return ""
	}
	if effect.Attempt == 1 {
		return effect.ID
	}
	return fmt.Sprintf("%s_attempt_%d", effect.ID, effect.Attempt)
}

// An AgentTask node creates one immutable effect in one activation. A
// matching effect ID inserted elsewhere in the parent state is not an owner.
func matchesAgentTaskActivation(activations []Activation, effect Effect) bool {
	if effect.ActivationID == "" {
		return false
	}
	matches := 0
	for _, activation := range activations {
		if activation.ID == effect.ActivationID && activation.NodeID == effect.NodeID &&
			activation.EffectID == effect.ID && len(activation.EffectIDs) == 1 &&
			activation.EffectIDs[0] == effect.ID {
			matches++
		}
	}
	return matches == 1
}

// Do not infer ownership from any generic effect which happens to carry
// Class=agent.task. The frozen Definition must contain the matching, explicit
// AgentTask node and its exact kind/revision.
func matchesAgentTaskNode(definition Definition, effect Effect) bool {
	matches := 0
	for _, node := range definition.Nodes {
		if node.ID == effect.NodeID && node.Type == NodeAgentTask && node.AgentTask != nil &&
			node.AgentTask.AgentKey == effect.Kind && node.AgentTask.Revision == effect.Revision {
			matches++
		}
	}
	return matches == 1
}
